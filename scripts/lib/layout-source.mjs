import ts from "typescript";
import { transformSync } from "esbuild";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const repositoryRoot = fileURLToPath(new URL("../../", import.meta.url));
const biomePath = fileURLToPath(
  new URL("../../node_modules/@biomejs/biome/bin/biome", import.meta.url),
);

/** Generate sandbox source from the single host implementation, without runtime serialization. */
export function createLayoutSourceModule(sourceText) {
  const sourceFile = ts.createSourceFile(
    "layout-settling.ts",
    sourceText,
    ts.ScriptTarget.ES2022,
    true,
    ts.ScriptKind.TS,
  );
  const functions = sourceFile.statements.filter(ts.isFunctionDeclaration);
  const implementation = functions[0];

  if (
    sourceFile.parseDiagnostics.length ||
    functions.length !== 1 ||
    implementation?.name?.text !== "settleLayout" ||
    !implementation.body
  ) {
    throw new Error("Sandbox generation requires exactly one settleLayout function implementation");
  }

  for (const statement of sourceFile.statements) {
    if (
      statement !== implementation &&
      !ts.isInterfaceDeclaration(statement) &&
      !ts.isTypeAliasDeclaration(statement) &&
      !(ts.isImportDeclaration(statement) && statement.importClause?.isTypeOnly)
    ) {
      throw new Error(
        "The sandbox policy must have no runtime imports or module-level dependencies",
      );
    }
  }

  const declaration = ts.factory.updateFunctionDeclaration(
    implementation,
    implementation.modifiers?.filter((modifier) => modifier.kind !== ts.SyntaxKind.ExportKeyword),
    implementation.asteriskToken,
    implementation.name,
    implementation.typeParameters,
    implementation.parameters,
    implementation.type,
    implementation.body,
  );
  const printed = ts
    .createPrinter({
      removeComments: true,
    })
    .printNode(ts.EmitHint.Unspecified, declaration, sourceFile);
  const source = transformSync(printed, {
    loader: "ts",
    target: "es2022",
    minifyWhitespace: true,
    minifyIdentifiers: false,
    minifySyntax: false,
    legalComments: "none",
  }).code.trim();

  const generatedModule =
    "// Generated by pnpm sandbox:generate from layout-settling.ts; do not edit.\n" +
    `export const layoutSettlingSource: string = ${JSON.stringify(source)};\n`;

  return execFileSync(
    process.execPath,
    [
      biomePath,
      "format",
      "--stdin-file-path=packages/core/src/generated/layout-settling-source.ts",
      `--config-path=${repositoryRoot}`,
    ],
    {
      cwd: repositoryRoot,
      input: generatedModule,
      encoding: "utf8",
    },
  );
}
